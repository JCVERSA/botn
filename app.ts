  function regexTranspile(source: string): string {
    let js = source;
    // Type-only imports (safe to drop)
    js = js.replace(/import\s+[^;]+?\s+from\s+['"]\.\.\/types\.js['"];?/g, "");
    // Project helper imports (resolved to root-level lib files in the zip)
    js = js.replace(/import\s+({[^}]+})\s+from\s+['"]\.\.\/geminiClient\.js['"];?/g, "const $1 = require('./geminiClient.js');");
    js = js.replace(/import\s+({[^}]+})\s+from\s+['"]\.\.\/database\.js['"];?/g, "const $1 = require('./database.js');");
    // Named imports from npm / other modules
    js = js.replace(/import\s+({[^}]+})\s+from\s+["']@google\/genai["'];?/g, "const $1 = require('@google/genai');");
    js = js.replace(/import\s+({[^}]+})\s+from\s+["']([^"']+)["'];?/g, "const $1 = require('$2');");
    js = js.replace(/import\s+([A-Za-z_$][\w$]*)\s+from\s+["']([^"']+)["'];?/g, "const $1 = require('$2');");
    // Exports and TS-only syntax
    js = js.replace(/export\s+default\s+(\w+);?/g, "module.exports = $1;");
    js = js.replace(/export\s+interface\s+\w+\s*\{[^}]*\}/g, "");
    js = js.replace(/export\s+const\s+(\w+)(:\s*[\w<>|'"]+)?\s*=/g, "const $1 =");
    js = js.replace(/export\s+async\s+function\s+(\w+)/g, "async function $1");
    js = js.replace(/export\s+function\s+(\w+)/g, "function $1");
    js = js.replace(/const\s+(\w+):\s*BotCommand\s*=/g, "const $1 =");
    js = js.replace(/:\s*BotCommand\b/g, "");
    js = js.replace(/:\s*BotCommandContext\b/g, "");
    return js;
  }

  /**
   * Converts a TypeScript source file to CommonJS for the exported package.
   * Prefers esbuild (handles all TS syntax correctly); falls back to a
   * conservative regex transpiler when esbuild is unavailable.
   */
  async function transpileTsToCjs(source: string): Promise<string> {
    // Rewrite config.ts imports to read the packaged config.json.
    const preprocessed = source.replace(CONFIG_IMPORT_RE, CONFIG_SHIM);
    try {
      const { transform } = await import("esbuild");
      const result = await transform(preprocessed, {
        loader: "ts",
        format: "cjs",
        platform: "node",
        target: "node18",
      });
      return result.code;
    } catch (e: any) {
      console.warn("[ZIP] esbuild transform unavailable; using regex transpiler:", e?.message || e);
      return regexTranspile(preprocessed);
    }
  }

