    if (!fs.existsSync(commandsDir)) {
      fs.mkdirSync(commandsDir, { recursive: true });
    }

    const filePath = path.join(commandsDir, `${cleanName}.ts`);

    try {
      fs.writeFileSync(filePath, code, "utf-8");
      addLog(`📝 Saved command file: /src/bot/commands/${cleanName}.ts`);

      // Compile a self-contained artifact so production Node can load it too.
      await compileCommandToMjs(cleanName, filePath);

      // Reload the registry so the command becomes active immediately
      await initRegistry();
      const loaded = !!getCommand(cleanName);

      res.json({
        success: true,
        message: loaded
          ? `Command "${cleanName}" saved and loaded.`
          : `Command "${cleanName}" saved, but could not be loaded. Check the server logs.`,
        loaded,
      });
    } catch (error: any) {
      res.status(500).json({ error: `Failed to save command: ${error.message}` });
    }
