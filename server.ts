// API: Audio Transcription using Gemini with fallback models
app.post("/api/gemini/transcribe", async (req, res) => {
  const { audioBase64, mimeType } = req.body;
  if (!audioBase64) {
    return res.status(400).json({ error: "Missing audioBase64 payload" });
  }

  const ai = getAIClient();
  if (!ai) {
    return res.status(400).json({ error: "Gemini API key is not configured. Please add it to Settings > Secrets." });
  }

  const transcriptionModels = ["gemini-3.5-flash", "gemini-2.5-flash", "gemini-1.5-flash"];
  let lastError: any = null;

  for (const model of transcriptionModels) {
    try {
      const response = await ai.models.generateContent({
        model,
        contents: [
          {
            inlineData: {
              data: audioBase64,
              mimeType: mimeType || "audio/webm",
            },
          },
          { text: "Accurately transcribe this audio message. Output only the plain transcription, no extra commentary, preambles, or punctuation headers." },
        ],
      });

      if (response && response.text) {
        return res.json({ transcript: response.text.trim() });
      }
    } catch (err: any) {
      console.warn(`⚠️ Transcription failed on model [${model}]:`, err?.message || err);
      lastError = err;
    }
  }

  res.status(500).json({ error: `Transcription failed across all fallback models: ${lastError?.message || lastError}` });
});

// API: Real-time Voice Conversation using Gemini with fallbacks and TTS
app.post("/api/gemini/voice-conversation", async (req, res) => {
  const { prompt } = req.body;
  if (!prompt) {
    return res.status(400).json({ error: "Missing prompt query" });
  }

  const ai = getAIClient();
  if (!ai) {
    return res.status(400).json({ error: "Gemini API key is not configured. Please add it to Settings > Secrets." });
  }

  try {
    // 1. Generate textual spoken reply using robust text fallback generator helper
    const replyText = await generateTextWithFallback(
      prompt,
      "You are a friendly, helpful, highly conversational AI voice assistant. Keep your responses super short (1-2 sentences), sweet, warm, and direct. Avoid asterisks, bullets, lists, markdown formatting, or emojis since your response will be read aloud.",
      "gemini-3.5-flash"
    );

    // 2. Synthesize spoken reply to audio using TTS preview model
    let audioBase64: string | null = null;
    try {
      const speechResponse = await ai.models.generateContent({
        model: "gemini-3.1-flash-tts-preview",
        contents: [{ parts: [{ text: replyText }] }],
        config: {
          responseModalities: ["AUDIO"],
          speechConfig: {
            voiceConfig: {
              prebuiltVoiceConfig: { voiceName: "Zephyr" },
            },
          },
        },
      });
      audioBase64 = speechResponse.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data || null;
    } catch (ttsErr: any) {
      console.warn("⚠️ TTS audio synthesis rate-limited or busy. Falling back to text-only spoken reply.", ttsErr?.message || ttsErr);
    }

    res.json({
      text: replyText,
      audioBase64
    });
  } catch (error: any) {
    console.error("Voice conversation error:", error);
    res.status(500).json({ error: error.message || error });
  }
});

// Start dev server with Vite in full-stack mode
async function startServer() {
  // Vite dev server middleware setup
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    addLog(`🚀 Nebula Controller Panel is live on http://localhost:${PORT}`);
  });
}

startServer();
