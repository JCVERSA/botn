// API: AI-Powered Command Builder (using Gemini 3.7-flash)
app.post("/api/bot/commands/generate", async (req, res) => {
  const { prompt, commandName, category, description } = req.body;
  
  if (!prompt || !commandName) {
    return res.status(400).json({ error: "Prompt and commandName are required." });
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === "MY_GEMINI_API_KEY" || apiKey.trim() === "") {
    return res.status(400).json({ error: "Gemini API key is not configured. Please add it to Settings > Secrets." });
  }

  const cleanName = commandName.trim().toLowerCase().replace(/[^a-z0-9]/g, "");
  const cleanCategory = (category || "Utility").trim();
  const cleanDesc = (description || `Dynamic AI-generated command for ${cleanName}`).trim();

  addLog(`🤖 Asking Gemini to design command: "${cleanName}" (${prompt})`);

  try {
    const ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        },
      },
    });

    const aiPrompt = `
Generate a fully functional TypeScript WhatsApp command file for a Baileys bot.
The file must export a default object implementing the following interface:

interface BotCommand {
  name: string;
  category: string;
  description: string;
  usage?: string;
  execute: (sock: any, msg: any, context: {
    sender: string;
    senderName: string;
    isOwner: boolean;
    prefix: string;
    commandName: string;
    args: string[];
    fullMessage: string;
    reply: (text: string, mediaUrl?: string) => Promise<any>;
    react: (emoji: string) => Promise<any>;
    downloadMedia?: () => Promise<Buffer | null>;
  }) => Promise<void> | void;
}

The command name is: "${cleanName}"
The category is: "${cleanCategory}"
The description is: "${cleanDesc}"
Specific instructions for what the command should do: "${prompt}"

Make the logic clean, fully typed, and robust. Always use markdown formatting in text outputs for neat messaging layout (e.g. bold like *text*, italics like _text_). If you use external API fetches, handle errors cleanly with try-catch and output helpful error messages. Use standard ES Module imports, specifically relative importing of the BotCommand type if needed, e.g. import { BotCommand } from "../types.js";

IMPORTANT: Output ONLY the raw TypeScript code. No markdown wrapping (like \`\`\`typescript ... \`\`\`), no conversational intros. Just raw TS code so I can save it directly to a file.
`;

    const response = await ai.models.generateContent({
      model: "gemini-3.7-flash",
      contents: aiPrompt,
    });

    let code = response.text || "";
    
    // Safety: strip markdown wraps if Gemini returned them despite instructions
    if (code.includes("```typescript")) {
      code = code.split("```typescript")[1].split("```")[0];
    } else if (code.includes("```ts")) {
      code = code.split("```ts")[1].split("```")[0];
    } else if (code.includes("```")) {
      code = code.split("```")[1].split("```")[0];
    }
    
    code = code.trim();

    // Save the file
    const commandsDir = path.join(process.cwd(), "src", "bot", "commands");
    if (!fs.existsSync(commandsDir)) {
      fs.mkdirSync(commandsDir, { recursive: true });
    }
    const filePath = path.join(commandsDir, `${cleanName}.ts`);
    fs.writeFileSync(filePath, code, "utf-8");

    // Re-initialize registry
    initRegistry();
    addLog(`✨ AI generated & successfully loaded command: /src/bot/commands/${cleanName}.ts`);

    res.json({
      success: true,
      message: `Command "${cleanName}" created successfully!`,
      code,
    });
  } catch (error: any) {
    addLog(`❌ AI Command Generation failed: ${error.message}`);
    res.status(500).json({ error: `AI generation failed: ${error.message}` });
  }
});

